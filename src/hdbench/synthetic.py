"""SYNTHETIC stand-in for the UCI files, used only to test the code path end to end.

It writes files in exactly the published UCI layout (comma separated, '?' for missing, 14 columns)
and reproduces the *kinds* of defects the audit must catch: site-specific missingness, zero
cholesterol/BP, exact duplicates, very different class balance per site. The numbers it produces
mean nothing clinically. Never report results computed from these files.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

from .data import UCI_FILES

# n, prevalence, missing share per column, share of zero cholesterol
SITE_SPEC = {
    "cleveland":   dict(n=303, prev=0.46, miss=dict(ca=0.013, thal=0.007), chol_zero=0.00),
    "hungarian":   dict(n=294, prev=0.36, miss=dict(chol=0.08, slope=0.65, ca=0.99, thal=0.90, fbs=0.03, thalach=0.003, exang=0.003, restecg=0.003), chol_zero=0.00),
    "switzerland": dict(n=123, prev=0.93, miss=dict(slope=0.14, ca=0.96, thal=0.42, fbs=0.60, trestbps=0.01), chol_zero=0.90),
    "va":          dict(n=200, prev=0.75, miss=dict(slope=0.51, ca=0.99, thal=0.83, fbs=0.03, chol=0.03), chol_zero=0.02),
}


def _site_frame(rng: np.random.Generator, n: int, prev: float, shift: float) -> np.ndarray:
    y = (rng.random(n) < prev).astype(int)
    age = np.clip(rng.normal(52 + 4 * y + shift, 9), 28, 77)
    sex = (rng.random(n) < (0.6 + 0.2 * y)).astype(int)
    cp = np.where(y == 1, rng.choice([1, 2, 3, 4], n, p=[0.07, 0.10, 0.15, 0.68]),
                  rng.choice([1, 2, 3, 4], n, p=[0.10, 0.28, 0.40, 0.22]))
    trestbps = np.clip(rng.normal(128 + 5 * y, 17), 90, 200)
    chol = np.clip(rng.normal(240 + 5 * y, 55), 120, 560)
    fbs = (rng.random(n) < 0.12 + 0.05 * y).astype(int)
    restecg = np.where(y == 1, rng.choice([0, 1, 2], n, p=[0.45, 0.07, 0.48]),
                       rng.choice([0, 1, 2], n, p=[0.55, 0.02, 0.43]))
    thalach = np.clip(rng.normal(158 - 20 * y - 0.4 * (age - 52), 18), 70, 205)
    exang = (rng.random(n) < 0.12 + 0.50 * y).astype(int)
    oldpeak = np.round(np.clip(rng.gamma(1.2, 0.5 + 0.9 * y), 0, 6.2), 1)
    slope = np.where(y == 1, rng.choice([1, 2, 3], n, p=[0.25, 0.65, 0.10]), rng.choice([1, 2, 3], n, p=[0.65, 0.30, 0.05]))
    ca = np.minimum(rng.poisson(0.15 + 1.0 * y), 3)
    thal = np.where(y == 1, rng.choice([3, 6, 7], n, p=[0.25, 0.07, 0.68]), rng.choice([3, 6, 7], n, p=[0.80, 0.05, 0.15]))
    num = np.where(y == 1, rng.choice([1, 2, 3, 4], n, p=[0.45, 0.25, 0.20, 0.10]), 0)
    return np.column_stack([age.round(), sex, cp, trestbps.round(), chol.round(), fbs, restecg,
                            thalach.round(), exang, oldpeak, slope, ca, thal, num])


def write_synthetic_uci(out_dir: Path, seed: int = 7) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    cols = ["age", "sex", "cp", "trestbps", "chol", "fbs", "restecg", "thalach", "exang", "oldpeak", "slope", "ca", "thal", "num"]
    for i, (site, spec) in enumerate(SITE_SPEC.items()):
        arr = _site_frame(rng, spec["n"], spec["prev"], shift=2.0 * i)
        arr = arr.astype(object)
        n = arr.shape[0]
        zero_rows = rng.random(n) < spec["chol_zero"]
        arr[zero_rows, cols.index("chol")] = 0
        for col, frac in spec["miss"].items():
            arr[rng.random(n) < frac, cols.index(col)] = np.nan
        # a few exact duplicates and one impossible blood pressure
        dup_src = rng.choice(n, size=3, replace=False)
        arr = np.vstack([arr, arr[dup_src]])
        arr[rng.integers(0, n), cols.index("trestbps")] = 0
        lines = []
        for row in arr:
            lines.append(",".join("?" if (isinstance(v, float) and np.isnan(v)) else
                                  (str(int(v)) if float(v).is_integer() else str(v)) for v in row))
        (out_dir / UCI_FILES[site]).write_text("\n".join(lines) + "\n", encoding="utf-8")
    (out_dir / "README_SYNTHETIC.txt").write_text(
        "SYNTHETIC DATA generated by hdbench.synthetic for pipeline testing only.\n"
        "These files are NOT the UCI Heart Disease data. Do not report results from them.\n", encoding="utf-8")
